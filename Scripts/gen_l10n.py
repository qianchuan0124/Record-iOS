#!/usr/bin/env python3
"""Generate L10n.swift from Resources/zh-Hans.lproj/Localizable.strings.

Key format: <namespace>_<snake_case_name>, e.g. ledger_filter_view_count.
Strings containing %@/%d become functions taking CVarArg parameters.
"""

import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
STRINGS = ROOT / "Record-iOS/Resources/zh-Hans.lproj/Localizable.strings"
OUTPUT = ROOT / "Record-iOS/L10n/L10n.swift"

NAMESPACES = {
    "common": "Common",
    "tab": "Tab",
    "summary": "Summary",
    "ledger": "Ledger",
    "detail": "Detail",
    "editor": "Editor",
    "analysis": "Analysis",
    "assets": "Assets",
    "bank": "Bank",
    "settings": "Settings",
    "sync": "Sync",
    "data": "Data",
    "about": "About",
    "toast": "Toast",
}
ORDER = ["Common", "Tab", "Summary", "Ledger", "Detail", "Editor", "Analysis", "Assets", "Bank", "Settings", "Sync", "Data", "About", "Toast"]

LINE = re.compile(r'^\s*"([^"]+)"\s*=\s*"(.*)";\s*$')


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(word[:1].upper() + word[1:] for word in parts[1:])


def placeholders(value: str) -> int:
    return len(re.findall(r"%(?:@|d|ld|lu|f|\.\d+f)", value))


def main() -> None:
    entries = []
    for line in STRINGS.read_text(encoding="utf-8").splitlines():
        match = LINE.match(line)
        if match:
            entries.append((match.group(1), match.group(2)))

    groups = {}
    for key, value in entries:
        prefix, _, rest = key.partition("_")
        namespace = NAMESPACES.get(prefix)
        if namespace is None:
            raise SystemExit(f"Unknown namespace for key: {key}")
        groups.setdefault(namespace, []).append((camel(rest), key, value))

    lines = [
        "// Generated by Scripts/gen_l10n.py from Resources/zh-Hans.lproj/Localizable.strings.",
        "// Do not edit by hand.",
        "",
        "import Foundation",
        "",
        "enum L10n {",
    ]

    for namespace in ORDER:
        items = sorted(groups.get(namespace, []), key=lambda item: item[0])
        if not items:
            continue
        lines.append(f"    enum {namespace} {{")
        for name, key, value in items:
            count = placeholders(value)
            lines.append(f"        /// {value}")
            if count == 0:
                lines.append(f'        static let {name} = L10nCore.string("{key}")')
            else:
                params = ", ".join(f"_ p{i + 1}: CVarArg" for i in range(count))
                args = ", ".join(f"p{i + 1}" for i in range(count))
                lines.append(f"        static func {name}({params}) -> String {{")
                lines.append(f'            L10nCore.string("{key}", {args})')
                lines.append("        }")
        lines.append("    }")
        lines.append("")

    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUTPUT} ({len(entries)} strings)")


if __name__ == "__main__":
    main()
